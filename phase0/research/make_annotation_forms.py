# Paper 1 annotation: per-language Google Apps Scripts that create short Google Forms ("packs").
#
# Each pack = N_ANCHOR anchor texts shared by every pack of that language (inter-annotator agreement and a quality
# check) + N_UNIQUE texts unique to the pack, shuffled together. Per text: one tap for the language judgement, one tap
# for text quality. Texts come from research/audit/annotation/{lang}.csv (already stratified across corpora, shuffled,
# corpus hidden). Writes forms/{lang}.gs (paste into script.google.com, run createForms) and forms/packs.json
# (pack -> item ids, for scoring).

import csv, json, os, random, re

AUDIT = os.environ.get("AUDIT_DIR", r"C:\Users\Muneeb\Documents\pakistan-languages-llm\research\audit")
OUT = os.path.join(AUDIT, "forms")
N_ANCHOR, N_UNIQUE, MAX_CHARS, MIN_PACK, SEED = 5, 25, 500, 15, 20261121

LANGS = {   # code: (English name, native name)
    "urd_Arab": ("Urdu", "اردو"), "urd_Latn": ("Roman Urdu", "Roman Urdu"), "pbt_Arab": ("Pashto", "پښتو"),
    "snd_Arab": ("Sindhi", "سنڌي"), "pnb_Arab": ("Punjabi (Shahmukhi)", "پنجابی"), "skr_Arab": ("Saraiki", "سرائیکی"),
    "bal_Arab": ("Balochi", "بلوچی"), "brh_Arab": ("Brahui", "براہوئی"), "kas_Arab": ("Kashmiri", "کٲشُر"),
}
OTHERS = ["Urdu", "Roman Urdu", "Punjabi", "Saraiki", "Pashto", "Sindhi", "Balochi", "Brahui", "Kashmiri", "Persian", "Arabic", "English"]

def trim(t):
    t = re.sub(r"\s*/\s*", " / ", t).strip()
    if len(t) <= MAX_CHARS: return t
    cut = t[:MAX_CHARS]; sp = cut.rfind(" ")
    return (cut[:sp] if sp > MAX_CHARS * 0.6 else cut) + " …"

def options(lang):
    name = LANGS[lang][0]; short = "Punjabi" if lang == "pnb_Arab" else name
    nots = [o for o in OTHERS if o != short and not (lang == "urd_Latn" and o == "Urdu")]
    if lang == "urd_Latn": nots = ["Urdu in Urdu script"] + nots
    return [f"Yes, it is {name}", f"Mostly {name}, mixed with another language"] + [f"Not {name}: it is {o}" for o in nots] + [f"Not {name}: another language / I can't tell"]

QUALITY = ["Real writing (sentences, news, stories, posts)", "List, menu or keywords", "Spam or advert", "Garbled, broken or machine-translated"]

def js(s): return json.dumps(s, ensure_ascii=False)

GS = r"""// Balagh annotation forms: __NAME__ (__CODE__). Generated by make_annotation_forms.py.
// HOW TO USE: script.google.com > New project > delete everything > paste this file > Save > choose createForms > Run.
// Approve the permissions (your own Google account). The links appear in the log and in a Google Sheet
// called "Balagh annotation __NAME__ - responses" in your Drive.
const LANG = __CODE_JS__, NAME = __NAME_JS__, NATIVE = __NATIVE_JS__;
const OPTIONS = __OPTIONS__;
const QUALITY = __QUALITY__;
const PACKS = __PACKS__;

function createForms() {
  const sheet = SpreadsheetApp.create('Balagh annotation ' + NAME + ' - responses');
  const links = [];
  PACKS.forEach(function (pack, p) {
    const title = 'Balagh: ' + NAME + ' text check, pack ' + (p + 1) + ' of ' + PACKS.length;
    const form = FormApp.create(title);
    form.setDescription(
      'Thank you for helping! This form has ' + pack.items.length + ' short texts taken from public websites that AI datasets say are ' + NAME + ' (' + NATIVE + ').\n\n' +
      'For each text, tap two answers: (1) is it really ' + NAME + '? (2) is it real writing or junk?\n' +
      'Judge the language, not the topic. Texts may be cut off at the end; that is fine. It takes about 15-20 minutes.\n\n' +
      'Please use only your own knowledge: no Google Translate, ChatGPT or other tools.\n\n' +
      'Balagh is an unfunded, open-source research project by Ownova. With your permission, contributors are thanked by name in the research papers and on the open dataset contributors list. Questions: muneeb@ownova.org');
    form.setProgressBar(true);
    form.setConfirmationMessage('Thank you so much! Your answers have been saved. You are helping make AI work for Pakistan\'s languages.');
    form.setAllowResponseEdits(false);
    form.setCollectEmail(false);
    form.addTextItem().setTitle('Your name (or a nickname if you prefer)').setRequired(true);
    form.addTextItem().setTitle('Your native language(s), the ones you grew up speaking').setRequired(true);
    form.addTextItem().setTitle('Where did you grow up? (city or district)').setRequired(true);
    form.addMultipleChoiceItem().setTitle('May we thank you by name in the research papers and on the contributors list?')
      .setChoiceValues(['Yes, use my name', 'No, keep me anonymous']).setRequired(true);
    form.addCheckboxItem().setTitle('I will answer using only my own knowledge (no translation tools or AI)')
      .setChoiceValues(['I agree']).setRequired(true);
    pack.items.forEach(function (it, i) {
      form.addPageBreakItem().setTitle('Text ' + (i + 1) + ' of ' + pack.items.length);
      form.addSectionHeaderItem().setTitle('Read this text:').setHelpText(it.text);
      form.addMultipleChoiceItem().setTitle('Text ' + (i + 1) + ' [' + it.id + ']: which language is this?')
        .setChoiceValues(OPTIONS).setRequired(true);
      form.addMultipleChoiceItem().setTitle('Text ' + (i + 1) + ' [' + it.id + ']: is it real writing?')
        .setChoiceValues(QUALITY).setRequired(true);
    });
    form.addPageBreakItem().setTitle('Almost done');
    form.addParagraphTextItem().setTitle('Any comments? (optional) For example: texts that were hard to judge, or dialect notes.');
    form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());
    links.push([pack.name, form.getPublishedUrl(), form.getEditUrl()]);
    Logger.log(pack.name + '  SHARE: ' + form.getPublishedUrl());
  });
  const tab = sheet.insertSheet('Form links');
  tab.getRange(1, 1, 1, 3).setValues([['pack', 'share this link with volunteers', 'edit link (only for you)']]);
  tab.getRange(2, 1, links.length, 3).setValues(links);
  Logger.log('Responses + all links: ' + sheet.getUrl());
}
"""

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    manifest = {}
    for lang, (name, native) in LANGS.items():
        rows = list(csv.reader(open(os.path.join(AUDIT, "annotation", f"{lang}.csv"), encoding="utf-8-sig")))[1:]
        items = [{"id": r[0], "text": trim(r[1].replace(" / ", "\n"))} for r in rows if len(r[1].split()) >= 10]
        anchors, rest = items[:N_ANCHOR], items[N_ANCHOR:]
        packs = []
        for k in range(0, len(rest), N_UNIQUE):
            chunk = rest[k:k + N_UNIQUE]
            if len(chunk) < MIN_PACK: break
            mix = anchors + chunk; random.Random(SEED + k).shuffle(mix)
            packs.append({"name": f"{lang}-pack{len(packs) + 1}", "items": mix})
        gs = (GS.replace("__CODE_JS__", js(lang)).replace("__NAME_JS__", js(name)).replace("__NATIVE_JS__", js(native))
                .replace("__OPTIONS__", js(options(lang))).replace("__QUALITY__", js(QUALITY)).replace("__PACKS__", js(packs))
                .replace("__NAME__", name).replace("__CODE__", lang))
        open(os.path.join(OUT, f"{lang}.gs"), "w", encoding="utf-8").write(gs)
        manifest[lang] = {"anchors": [a["id"] for a in anchors], "packs": {p["name"]: [i["id"] for i in p["items"]] for p in packs}}
        print(f"{lang}: {len(items)} texts -> {len(packs)} packs of {N_ANCHOR}+{N_UNIQUE}; script {os.path.getsize(os.path.join(OUT, lang + '.gs')) // 1024} KB")
    json.dump(manifest, open(os.path.join(OUT, "packs.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
